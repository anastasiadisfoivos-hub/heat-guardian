F = np.float32
REF = FT.REF
NAMES = ["W1", "b1", "W2", "b2", "W3", "b3"]


def members():
    return [[np.ascontiguousarray(a, F) for a in load_member(k)[1]] for k in range(1, 6)]


def dense_seq(W, b, x, relu):
    P = (W * x[None, :]).astype(F); acc = b.astype(F).copy()
    for i in range(W.shape[1]): acc = (acc + P[:, i]).astype(F)
    return np.where(acc < 0, F(0), acc).astype(F) if relu else acc


def member_out(m, z):
    h1 = dense_seq(m[0], m[1], z, True); h2 = dense_seq(m[2], m[3], h1, True); return dense_seq(m[4], m[5], h2, False)


def ens_seq(Ms, z):
    s = np.zeros(9, F); s2 = np.zeros(9, F); ys = []
    for m in Ms:
        y = member_out(m, z); ys.append(y); s = (s + y).astype(F); s2 = (s2 + (y * y).astype(F)).astype(F)
    mu = (s / F(5)).astype(F); var = ((s2 / F(5)).astype(F) - (mu * mu).astype(F)).astype(F)
    sd = np.where(var > 0, np.sqrt(np.maximum(var, F(0))).astype(F), F(0)).astype(F)
    return mu, sd, ys


def zvec(x, xm, xs):
    with np.errstate(invalid="ignore", over="ignore"):
        z = ((x - xm).astype(F) / xs).astype(F)
    return np.where(np.isfinite(z), z, F(0)).astype(F)     # [B2-fix] C: z = isfinite-equivalent (z == z && fabsf(z) < 3.4e38f)


def hx(a): return np.ascontiguousarray(a, "<f4").tobytes().hex()


def br(a):
    if a.ndim == 1: return "{" + ",".join("%.9ef" % v for v in a) + "}"
    return "{" + ",\n ".join(br(r) for r in a) + "}"


def git_sha():
    try: return subprocess.check_output(["git", "-C", MODEL, "rev-parse", "--short", "HEAD"]).decode().strip()
    except Exception: return "nogit"


SD_SCALE = 1.0
M5X = {}


