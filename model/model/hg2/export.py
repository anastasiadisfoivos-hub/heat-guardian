    sig = np.array(REF.SIG, F)
    h = ["/* GENERATED by model/hg2/export.py -- hg2 Core Sense ensemble 32-24-16-9 x5 (6 task outputs + 3 sd heads). do not edit.",
         " * Run %s: trained on Virtual Elders %s (%s, SIMULATION; known too-tolerant at humid rest, bed rest and HR)" % (TAG, SIMVER, prov["minutes_dev_file"]),
         " *   with the M3.2 HR-rise augmentation, M6 body-hypothesis member mixes and sd heads, + HTT-DEV fine-tune",
         " *   (young adults 18-33, chamber walk; HR/air pathway only, thermal inputs masked).",
         " * Training data sha256 %s. OOD: outside SIM support (HR > ~108 bpm, hr_reserve > 0.55) the" % prov["minutes_dev_sha256"],
         " *   outputs are extrapolation; above HR 180 core/logit_p385 FALL with rising HR (not monotone) -> the band must",
         " *   apply max(NN, v1.2) there (M11 OOD guard, B5). */",
         "#ifndef HG2_WEIGHTS_H", "#define HG2_WEIGHTS_H", "#include <stdint.h>",
         "#define HG2_WEIGHTS_STUB 0", "#define HG2_NN_IN 32", "#define HG2_NN_H1 24", "#define HG2_NN_H2 16", "#define HG2_NN_OUT 9  /* 6 task outputs + 3 sd heads v (aleatoric var = v*v + HG2_EPS_V, normalised units) */",
         "#define HG2_NN_NTASK 6", "#define HG2_EPS_V (1.0e-3f)", "#define HG2_NN_ENS 5",
         "#ifndef HG2_N_IN", "#define HG2_N_IN 32", "#endif", "#ifndef HG2_N_OUT", "#define HG2_N_OUT 6", "#endif",
         "#ifndef HG2_N_ENS", "#define HG2_N_ENS 5", "#endif", "#define HG2_H1 24", "#define HG2_H2 16",
         "#define HG2_NN_CRC32 0x%08Xu  /* zlib CRC-32 over all float32 weight bytes, LE, members 0..4, W1 b1 W2 b2 W3 b3 */" % crc,
         '#define HG2_NN_VERSION "%s"' % version,
         '#define HG2_TRAIN_DATA_SHA256 "%s"' % prov["minutes_dev_sha256"],
         "/* NN logit cuts (danger_calib.py, nested LOSO on HTT-DEV; 1.0e9f = that NN path never fires) */",
         "/* M6.3: f20_eff = core_20 + HG2_SD_K * min(sd_20, 0.30); sd = sqrtf(mean_k(v_k^2 + EPS_V) + between-member var) * Y_STD */",
         "#define HG2_SD_K (%.2ff)" % cuts.get("HG2_SD_K", 1.0),
         "#define HG2_LOGIT_CUT_38  (%.9ef)" % cuts["HG2_LOGIT_CUT_38"], "#define HG2_LOGIT_CUT_385 (%.9ef)" % cuts["HG2_LOGIT_CUT_385"],
         "/* RECOMMENDATION ONLY (not used by hg2_step unless the manager adopts it): ensemble sd is under-dispersed;",
         " * multiplying sd by this factor gives 90 % coverage of +-1.645 sd on the SIM-DEV validation subset (dev-calibrated). */",
         "#define HG2_SD_SCALE_RECOMMENDED (%.4ff)" % SD_SCALE,
         "/* Range half-widths (degC). *_REAL: nested-LOSO split-conformal 90 % on HTT (REAL young adults, HR only); the band",
         " * shows/uses max(1.645*sd, HG2_CONF_HALF_*_REAL) until wear-test wrist data exists ([B2-fix]). HG2_RANGE90_* /",
         " * HG2_CONF_HALF_CAL/UNCAL: SIMULATION calibration persons (M5.2). _PERSON: >= 90 % of held-out people get >= 80 %. */"] + [
         "#define %s (%.4ff)" % (k, v) for k, v in M5X.items()] + [
         "typedef struct { const float *W1, *b1, *W2, *b2, *W3, *b3; } hg2_member_t;",
         "extern const hg2_member_t HG2_MEMBERS[HG2_NN_ENS];",
         "extern const float HG2_X_MEAN[HG2_NN_IN];", "extern const float HG2_X_STD[HG2_NN_IN];",
         "extern const float HG2_Y_MEAN[3];", "extern const float HG2_Y_STD[3];",
         "extern const float HG2_SIGMOID_LUT[33];  /* z in [-8, 8], step 0.5, linear interpolation; display only */", "#endif"]
    c = ['/* GENERATED by model/hg2/export.py -- do not edit. %s */' % version, '#include "hg2_weights.h"']
    for k, m in enumerate(Ms):
        for n, a in zip(NAMES, m):
            c.append("static const float %s_%d%s = %s;" % (n, k, "".join("[%d]" % d for d in a.shape), br(a)))
