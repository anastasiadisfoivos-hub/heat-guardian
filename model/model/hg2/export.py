"""ARCH 4.4 step 5: export the trained 5-member hg2 ensemble (PROVISIONAL, sim v1 / M2).
Writes model/export/: hg2_weights.c (definitions) + hg2_weights.h (extern + defines; B5's symbol names AND the brief's),
hg2_weights.json (bit-exact float32 hex for B5's Python mirror), test_vectors.json (+ host/hg2_test_vectors.h),
golden_trace.parquet (3 DEV persons x 1 day: hg2_in_t per minute + Python hg2_out_t per minute, FeatureState + ensemble).
Outputs are computed with float32 sequential accumulation in the C loop order (B5 _dense), never with BLAS.
Usage: python3 -m model.hg2.export"""
