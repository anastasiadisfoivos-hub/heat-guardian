#!/usr/bin/env python3
"""B2b-v5: the AR skin envelope = p0.5..p99.5 of T1 - corrected air (features x[9], x[6]) in |air - c| <= 1 C bins over the
SIM-DEV TRAINING persons (cache <tag>/sim_v0.npz, member view 0, every 2nd minute). Rewrites the @AR_ENV block of
guardian/c/hg_guardian_cfg.h and prints the table.  usage: B2B_TAG=v5aug python3 -m model.b2b.envelope"""
import os, re
import numpy as np
from . import devdata as D

CFG = os.path.join(D.REPO, "guardian/c/hg_guardian_cfg.h")
AIR = [24, 26, 28, 30, 32, 34, 36, 38, 40]


def main():
    X = np.load(os.path.join(D.CACHE, "sim_v0.npz"))["X"][::2]
    ok = np.isfinite(X[:, 0]) & np.isfinite(X[:, 6]) & np.isfinite(X[:, 9])
    lo, hi, n = [], [], []
    for c in AIR:
        m = ok & (np.abs(X[:, 6] - c) <= 1.0); n.append(int(m.sum()))
        a, b = np.percentile(X[m, 9], [0.5, 99.5]); lo.append(round(float(a), 2)); hi.append(round(float(b), 2))
    f = lambda v: ", ".join("%.2ff" % x for x in v)
    blk = ("/* @AR_ENV_BEGIN (generated by model/b2b/envelope.py from cache %s/sim_v0.npz; rows per bin %s) */\n" % (D.TAG, n)
           + "static const float HG_AR_ENV_AIR[HG_AR_ENV_N] = {%s};\n" % f(AIR)
           + "static const float HG_AR_ENV_LO[HG_AR_ENV_N] = {%s};\n" % f(lo)
           + "static const float HG_AR_ENV_HI[HG_AR_ENV_N] = {%s};\n" % f(hi) + "/* @AR_ENV_END */")
    s = open(CFG).read()
    s = re.sub(r"/\* @AR_ENV_BEGIN.*?@AR_ENV_END \*/", lambda _: blk, s, flags=re.S)
    open(CFG, "w").write(s)
    print(blk)


if __name__ == "__main__":
    main()
