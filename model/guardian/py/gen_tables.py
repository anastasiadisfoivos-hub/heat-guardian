#!/usr/bin/env python3
"""Generate the lookup tables shared bit-for-bit by the band C code and the Python mirror.
Writes ../c/hg_tables.h, ../c/hg_tables.c and ./hg_tables.json (float32 values as exact hex).
Every table replaces a libm call the band may not use (ARCHITECTURE section 4.5: no expf/logf/powf).
"""
import json, math, os, struct, subprocess, tempfile
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
C_DIR = os.path.join(HERE, "..", "c")
f32 = np.float32

def ewm_alpha_c(tau):
    """Exactly what heat_guardian_band.c computes at runtime: 1.0f - expf(-1.0f / tau) (host glibc)."""
    src = '#include <math.h>\n#include <stdio.h>\nint main(void){volatile float t=%ff; float a=1.0f-expf(-1.0f/t); unsigned u; __builtin_memcpy(&u,&a,4); printf("%%08x",u); return 0;}' % tau
    with tempfile.TemporaryDirectory() as d:
        open(d + "/a.c", "w").write(src)
        subprocess.check_call(["gcc", "-O0", d + "/a.c", "-o", d + "/a", "-lm"])
        h = subprocess.check_output([d + "/a"]).decode()
    return struct.unpack("<f", bytes.fromhex(h)[::-1])[0]

# Magnus saturation vapour pressure, same constants as v1.2 vapour_kpa (heat_guardian_band.c):
# psat(t) = 0.61094 * exp(17.625 t / (t + 243.04)) kPa  (Alduchov & Eskridge 1996 form). 26 entries 20..45 C (ARCH 4.5).
PSAT_T0, PSAT_N = 20, 26
psat = [f32(0.61094 * math.exp(17.625 * t / (t + 243.04))) for t in range(PSAT_T0, PSAT_T0 + PSAT_N)]
# Sigmoid for DISPLAY only: 33 entries over z in [-8, 8], step 0.5 (ARCH 4.5).
sig = [f32(1.0 / (1.0 + math.exp(-(-8.0 + 0.5 * i)))) for i in range(33)]
# ln(m) for m in [1, 2], 33 entries (step 1/32): used by hg_ln1p() for features 16/17 (ln(1+PI), ln(1+100 a_std)).
lnm = [f32(math.log(1.0 + i / 32.0)) for i in range(33)]
# sin(2 pi m / 1440) every 15 min, 97 entries (0..1440); cos uses the same table shifted by 360 min.
sintod = [f32(math.sin(2 * math.pi * (15 * i) / 1440.0)) for i in range(97)]
alphas = {"HG_EWM_A5": ewm_alpha_c(5.0), "HG_EWM_A15": ewm_alpha_c(15.0), "HG_EWM_A45": ewm_alpha_c(45.0),
          "HG_EWM_A30": ewm_alpha_c(30.0)}

def hexf(v): return struct.pack("<f", float(v)).hex()
def cf(v): return "%.9ef" % float(v)

h = ["/* GENERATED by guardian/py/gen_tables.py -- do not edit. Shared bit-for-bit with py/hg_tables.json. */",
     "#ifndef HG_TABLES_H", "#define HG_TABLES_H",
     "/* EWM factors 1-exp(-1/tau), computed once on the host exactly as heat_guardian_band.c ewm_step() does at runtime */"]
for k, v in alphas.items():
    h.append("#define %s (%s) /* = %s */" % (k, cf(v), hexf(v)))
h += ["#define HG_PSAT_T0 %d" % PSAT_T0, "#define HG_PSAT_N %d" % PSAT_N,
      "extern const float HG_PSAT_KPA[HG_PSAT_N];  /* Magnus, v1.2 constants, 1 C steps from 20 C */",
      "extern const float HG_SIG_LUT[33];          /* sigmoid(z), z = -8..8 step 0.5, display only */",
      "extern const float HG_LNM_LUT[33];          /* ln(1 + i/32) */",
      "extern const float HG_SIN_TOD[97];          /* sin(2 pi (15 i)/1440) */",
      "#define HG_LN2 (6.931471806e-01f)",
      "#endif"]
c = ['#include "hg_tables.h"']
for name, arr in (("HG_PSAT_KPA", psat), ("HG_SIG_LUT", sig), ("HG_LNM_LUT", lnm), ("HG_SIN_TOD", sintod)):
    c.append("const float %s[%d] = {%s};" % (name, len(arr), ",".join(cf(v) for v in arr)))
open(os.path.join(C_DIR, "hg_tables.h"), "w").write("\n".join(h) + "\n")
open(os.path.join(C_DIR, "hg_tables.c"), "w").write("\n".join(c) + "\n")
json.dump({"alphas": {k: hexf(v) for k, v in alphas.items()}, "psat": [hexf(v) for v in psat],
           "sig": [hexf(v) for v in sig], "lnm": [hexf(v) for v in lnm], "sintod": [hexf(v) for v in sintod],
           "psat_t0": PSAT_T0, "ln2": hexf(f32(0.6931471806))},
          open(os.path.join(HERE, "hg_tables.json"), "w"), indent=0)
# accuracy report (vs exact maths) for REPORT_GUARDIAN.md
tt = np.linspace(20, 45, 2501)
interp = np.interp(tt, np.arange(20, 46), np.array(psat, dtype=float))
exact = 0.61094 * np.exp(17.625 * tt / (tt + 243.04))
zz = np.linspace(-8, 8, 3201)
si = np.interp(zz, np.arange(33) * 0.5 - 8, np.array(sig, dtype=float))
print("psat max rel err %.2e, max abs err %.4f kPa" % (np.max(np.abs(interp / exact - 1)), np.max(np.abs(interp - exact))))
print("sigmoid LUT max abs err %.4f" % np.max(np.abs(si - 1 / (1 + np.exp(-zz)))))
print("alphas", {k: float(v) for k, v in alphas.items()})
