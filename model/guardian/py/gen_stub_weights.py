#!/usr/bin/env python3
"""STUB weights for hg2 (32 -> 24 -> 16 -> 6, ReLU, 5 members) with the exact symbol names B2's exporter must emit
(ARCHITECTURE 4.4 step 5 / 4.5). RANDOM (seed 20261112): they exercise the C ensemble, CRC and normalisation code only.
While HG2_WEIGHTS_STUB is 1, hg2_step() does NOT use the network outputs for any decision (it reports the v1.2 Kalman
anchor instead) - see guardian/c/hg2_step.c.  Writes ../c/stub/hg2_weights.h/.c and ../tests/hg2_stub_vectors.json.
"""
import json, os, struct, zlib
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, "..", "c", "stub")
N_IN, H1, H2, N_OUT, N_ENS = 32, 24, 16, 6, 5
f32 = np.float32
# plausible feature centres/scales so random weights see O(1) inputs (NOT a training result)
XM = [33.5, 0, 0, 1.5, 0, .5, 27, 0, 45, 6, 80, 80, 80, 10, .2, .7, .4, 1, 1, .3, 37.2, .1, .8, 0, 0, 34, 0, .7, .5, .87, .2, .05]
XS = [1.5, .3, .6, 1, .3, .5, 4, .5, 15, 3, 20, 18, 15, 15, .2, .45, .3, 1, .8, .3, .4, .2, .3, .7, .7, 1.5, .5, .1, .5, .15, .4, .2]
assert len(XM) == N_IN and len(XS) == N_IN
YM, YS = [37.1, 37.15, 37.2], [0.45, 0.5, 0.55]
def member(k):
    r = np.random.default_rng(20261112 + k)
    W1 = (r.standard_normal((H1, N_IN)) * np.sqrt(2 / N_IN)).astype(f32); b1 = (r.standard_normal(H1) * .1).astype(f32)
    W2 = (r.standard_normal((H2, H1)) * np.sqrt(2 / H1)).astype(f32); b2 = (r.standard_normal(H2) * .1).astype(f32)
    W3 = (r.standard_normal((N_OUT, H2)) * np.sqrt(2 / H2)).astype(f32); b3 = (r.standard_normal(N_OUT) * .1).astype(f32)
    return [W1, b1, W2, b2, W3, b3]
P = [member(k) for k in range(N_ENS)]
crc = 0
for p in P:
    for a in p: crc = zlib.crc32(a.astype("<f4").tobytes(), crc)
def br(a):
    if a.ndim == 1: return "{" + ",".join("%.9ef" % v for v in a) + "}"
    return "{" + ",\n ".join(br(r) for r in a) + "}"
names = ["W1", "b1", "W2", "b2", "W3", "b3"]
h = ["/* GENERATED by guardian/py/gen_stub_weights.py -- STUB RANDOM WEIGHTS, NOT A TRAINED MODEL. do not edit. */",
     "#ifndef HG2_WEIGHTS_H", "#define HG2_WEIGHTS_H", "#include <stdint.h>",
     "#define HG2_WEIGHTS_STUB 1   /* B2's trained export sets this to 0 */",
     "#define HG2_NN_IN 32", "#define HG2_NN_H1 24", "#define HG2_NN_H2 16", "#define HG2_NN_OUT 6", "#define HG2_NN_ENS 5",
     "#define HG2_NN_CRC32 0x%08Xu  /* zlib CRC-32 over all float32 weight bytes, little-endian, member order W1 b1 W2 b2 W3 b3 */" % crc,
     '#define HG2_NN_VERSION "hg2-stub-random-20261112"',
     "/* no trained cut exists: the NN Drink/Danger paths can never fire with the stub */",
     "#define HG2_LOGIT_CUT_38  (1.0e9f)", "#define HG2_LOGIT_CUT_385 (1.0e9f)",
     "typedef struct { const float *W1, *b1, *W2, *b2, *W3, *b3; } hg2_member_t;",
     "extern const hg2_member_t HG2_MEMBERS[HG2_NN_ENS];",
     "extern const float HG2_X_MEAN[HG2_NN_IN];", "extern const float HG2_X_STD[HG2_NN_IN];",
     "extern const float HG2_Y_MEAN[3];", "extern const float HG2_Y_STD[3];"]
c = ['#include "hg2_weights.h"']
for k, p in enumerate(P):
    for n, a in zip(names, p):
        dims = "".join("[%d]" % d for d in a.shape)
        c.append("static const float %s_%d%s = %s;" % (n, k, dims, br(a)))
c.append("const hg2_member_t HG2_MEMBERS[HG2_NN_ENS] = {" + ",".join(
    "{&W1_%d[0][0],b1_%d,&W2_%d[0][0],b2_%d,&W3_%d[0][0],b3_%d}" % ((k,) * 6) for k in range(N_ENS)) + "};")
c.append("const float HG2_X_MEAN[HG2_NN_IN] = %s;" % br(np.array(XM, f32)))
c.append("const float HG2_X_STD[HG2_NN_IN] = %s;" % br(np.array(XS, f32)))
c.append("const float HG2_Y_MEAN[3] = %s;" % br(np.array(YM, f32)))
c.append("const float HG2_Y_STD[3] = %s;" % br(np.array(YS, f32)))
h.append("#endif")
os.makedirs(OUT, exist_ok=True)
open(os.path.join(OUT, "hg2_weights.h"), "w").write("\n".join(h) + "\n")
open(os.path.join(OUT, "hg2_weights.c"), "w").write("\n".join(c) + "\n")
# weights as json for the Python mirror (hex float32 so they load bit-exact)
json.dump({"crc32": crc, "members": [[a.astype("<f4").tobytes().hex() for a in p] for p in P],
           "xm": np.array(XM, f32).astype("<f4").tobytes().hex(), "xs": np.array(XS, f32).astype("<f4").tobytes().hex(),
           "ym": np.array(YM, f32).astype("<f4").tobytes().hex(), "ys": np.array(YS, f32).astype("<f4").tobytes().hex()},
          open(os.path.join(HERE, "hg2_stub_weights.json"), "w"))
print("stub CRC 0x%08X" % crc)
