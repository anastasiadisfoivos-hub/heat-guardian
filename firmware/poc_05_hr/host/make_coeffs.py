#!/usr/bin/env python3
"""Generate hg_ppg_coeffs.h: 2nd-order Butterworth band-pass 0.5-4 Hz as two
biquad sections, for 50 and 100 sps. Run from poc_05_hr/: python3 host/make_coeffs.py"""
import numpy as np, os
from scipy.signal import butter

out = ["/* GENERATED by host/make_coeffs.py: Butterworth band-pass 0.5-4 Hz (order 2 -> 2 biquads) */\n#pragma once\n"]
for fs in (50, 100):
    sos = butter(2, [0.5, 4.0], btype="bandpass", fs=fs, output="sos")
    out.append(f"#if HG_PPG_FS == {fs}\n")
    for i, sec in enumerate(sos, 1):
        b0, b1, b2, a0, a1, a2 = sec
        out.append(f"static const float B{i}[3] = {{{b0:.9e}f, {b1:.9e}f, {b2:.9e}f}};\n")
        out.append(f"static const float A{i}[2] = {{{a1:.9e}f, {a2:.9e}f}};\n")
    out.append("#endif\n")
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "hg_ppg_coeffs.h"), "w").write("".join(out))
print("".join(out))
