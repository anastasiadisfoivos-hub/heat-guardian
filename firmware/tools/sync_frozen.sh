#!/bin/sh
# Copy the FROZEN inputs of 09_guardian byte-for-byte from git tag $TAG (default hg2-freeze-6; never the working tree; copied with git archive) and prove it:
#   sh fw/tools/sync_frozen.sh          (re)create fw/09_guardian/frozen/ + FROZEN_SHA256.txt
#   sh fw/tools/sync_frozen.sh --check  verify only (exit 1 on any mismatch)
# Checks: every copied file's sha256 == the tag's blob; hg2_weights.c/.h and hg2_guard.h == guardian/FROZEN.txt;
# HG2_NN_CRC32 in hg2_weights.h == $CRC (0xEE4F7E9E at freeze-6). host_test.c files are not copied (host-only).
set -e
TAG=${HG_FREEZE_TAG:-hg2-freeze-6}
FROZEN_TXT_SHA=${HG_FROZEN_TXT_SHA:-5adadad8049b837fc81c6598785990b0d20df9ca99ab535427e7c70d6023bf0a}
CRC=${HG_NN_CRC:-0xEE4F7E9E}
R=$(cd "$(dirname "$0")/../.." && pwd)
D="$R/fw/09_guardian/frozen"
cd "$R"
git rev-parse -q --verify "refs/tags/$TAG" >/dev/null || { echo "tag $TAG missing"; exit 1; }
FILES=$(git ls-tree --name-only $TAG guardian/c/ model/export/ twin/c/ | grep -E '\.(c|h)$' | grep -v host_test.c | grep -v -E 'guardian/c/stub/')
fail=0
X=${TMPDIR:-/tmp}/hg_frozen_x.$$
if [ "$1" != "--check" ]; then
  rm -rf "$D" "$X"; mkdir -p "$D" "$X"
  git archive "$TAG" guardian/c model/export twin/c | tar -x -C "$X"
fi
: > /tmp/hg_frozen_sums.$$
for f in $FILES; do
  b=$(basename "$f")
  want=$(git show "$TAG:$f" | sha256sum | cut -d' ' -f1)
  [ "$1" = "--check" ] || cp "$X/$f" "$D/$b"
  have=$(sha256sum "$D/$b" | cut -d' ' -f1)
  if [ "$want" != "$have" ]; then echo "MISMATCH $b (tag $want, copy $have)"; fail=1; fi
  echo "$have  $b  ($TAG:$f)" >> /tmp/hg_frozen_sums.$$
done
fz=$(git show "$TAG:guardian/FROZEN.txt" | sha256sum | cut -d' ' -f1)
if [ "$fz" = "$FROZEN_TXT_SHA" ]; then echo "FROZEN.txt sha OK ($fz)"; else echo "FROZEN.txt sha MISMATCH ($fz)"; fail=1; fi
for b in hg2_weights.c hg2_weights.h hg2_guard.h; do
  want=$(git show "$TAG:guardian/FROZEN.txt" | grep -E "sha256 $b " | awk '{print $3}')
  have=$(sha256sum "$D/$b" | cut -d' ' -f1)
  if [ "$want" = "$have" ]; then echo "FROZEN.txt OK  $b"; else echo "FROZEN.txt MISMATCH $b"; fail=1; fi
done
grep -q -i "HG2_NN_CRC32 *${CRC}u\?" "$D/hg2_weights.h" && echo "CRC $CRC present" || { echo "CRC $CRC NOT found"; fail=1; }
rm -rf "$X"
if [ "$1" != "--check" ]; then mv /tmp/hg_frozen_sums.$$ "$R/fw/09_guardian/FROZEN_SHA256.txt"; else rm -f /tmp/hg_frozen_sums.$$; fi
# one wrapper per frozen .c: compiles it unchanged with the host flags (fw_flags.h pragmas)
for f in "$D"/*.c; do
  b=$(basename "$f" .c); w="$R/fw/09_guardian/fz_$b.c"
  exp=$(printf '/* GENERATED by fw/tools/sync_frozen.sh: compiles the FROZEN %s.c (tag %s) unchanged, with the host flags */\n#include "fw_flags.h"\n#include "frozen/%s.c"\n' "$b" "$TAG" "$b")
  if [ "$1" = "--check" ]; then [ "$(cat "$w" 2>/dev/null)" = "$exp" ] || { echo "WRAPPER MISMATCH fz_$b.c"; fail=1; }
  else printf '%s\n' "$exp" > "$w"; fi
done
n=$(echo "$FILES" | wc -l)
[ $fail = 0 ] && echo "SYNC_FROZEN: PASS ($n files byte-identical to $TAG)" || { echo "SYNC_FROZEN: FAIL"; exit 1; }
