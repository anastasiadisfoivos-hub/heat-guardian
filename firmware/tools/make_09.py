#!/usr/bin/env python3
"""Build fw/09_guardian/09_guardian.ino from fw/08_logger/08_logger.ino (v1.1.2) + fw/09_guardian/guardian_layer.inc,
and copies 08's shared driver files (hg_i2c, hg_ppg, log_ring, log_format.h, hg_nofastmath.h, hg_astd.h) byte for byte.

08's sensing, I2C, storage, watchdog, boot safety, BLE UART console and dump are reused unchanged; every change is an
exact-string replacement below (each must match exactly once, so a drifted 08 fails loudly instead of building wrong).
  python3 fw/tools/make_09.py
"""
import os, sys
R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = open(os.path.join(R, "fw/08_logger/08_logger.ino")).read()
layer = open(os.path.join(R, "fw/09_guardian/guardian_layer.inc")).read()
s = src

def rep(a, b, cnt=1):
    global s
    n = s.count(a)
    if n != cnt:
        sys.exit(f"make_09: expected {cnt} match(es), found {n}:\n{a[:160]}")
    s = s.replace(a, b)

# ---- header, version, includes
i = s.index("#if !defined(ARDUINO_NRF52_ADAFRUIT)")
s = '''// =====================================================================
// Heat Guardian Band A - 09_guardian: the product firmware (GENERATED by fw/tools/make_09.py - edit that, not this)
// ---------------------------------------------------------------------
// = 08_logger v1.1.2 (sensing, bounded I2C, QSPI log, watchdog, boot safety, BLE UART console, dump)
// + the FROZEN Guardian Loop / Core Sense hg2 / Body Twin (tag hg2-freeze-6, fw/09_guardian/frozen, byte-identical,
//   compiled through fz_*.c with the host flags) driven once a minute by hg_fw.c
// + custom BLE service (STATUS notify / CMD write / INFO read), Twin file on InternalFS, Greek screens, haptic
//   patterns, power rules (screen sleeps, PPG 30 s of every minute, QSPI deep power-down, DC/DC).
// Board / wiring / libraries: exactly as 08_logger (README.md).
// =====================================================================

''' + s[i:]
rep('#define HG_FW_VERSION "08-logger-1.1.2"', '#define HG_FW_VERSION "09-guardian-0.9.3"')
rep('#define HG_FW_VERSION "08-logger-1.1.2-nodcdc"', '#define HG_FW_VERSION "09-guardian-0.9.3-nodcdc"')
rep('#define HG_FW_SHORT   "1.1.2"', '#define HG_FW_SHORT   "0.9.3"\n#define HG_FW_NUM     0x0093   /* INFO frame fw_version */')
rep('#include <Adafruit_LittleFS.h>', '#include <Adafruit_LittleFS.h>\n#include <InternalFileSystem.h>')
rep('#include "log_format.h"\n', '#define hg_crc8 hg_log_crc8   /* log_format.h and the frozen hg_frames.h both define an (identical) hg_crc8 */\n#include "log_format.h"\n#undef hg_crc8\n')
rep('#include "hg_i2c.h"\n}', '#include "hg_i2c.h"\n#include "hg_fw.h"\n#include "frozen/hg2_weights.h"\n#include "frozen/hg_guardian_cfg.h"\n}')

# ---- 1 Hz lines are a debug stream in 09 (log on), not on by default
rep('static bool liveUsb = true;', 'static bool liveUsb = false;       // 09: the 1 Hz hex stream is debug-only ("log on")\nstatic bool logBle = false;')
rep('  if (liveUsb) usbPut(line, 49);\n  bleQPut(line, 49);', '  if (liveUsb) usbPut(line, 49);\n  if (logBle) bleQPut(line, 49);')

# ---- QSPI log: no 1 Hz hour files; one file per day of minute records (inputs + guardian, 48 B/min)
rep('if (secN < sizeof secBuf / HG_REC_SIZE) { memcpy(secBuf + secN * HG_REC_SIZE, b, HG_REC_SIZE); secN++; } else recsLost++;',
    '/* 09: 1 Hz records are not stored on flash (power, wear); the minute records are (guardianMinute) */')
rep('''  // minute boundaries on the ms-since-boot clock
  uint32_t m0 = tick / 60000u * 60000u;
  if (!maOpen) minuteReset(m0);
  else if (m0 != ma.t0) { minuteClose(); minuteReset(m0); }
  minuteAdd(&r);
}''', '''  fwSecond(&r);                                    // 09: feed the minute summariser (hg_fw.c)
}''')
rep('#define HG_MIN_FLUSH_EVERY 10', '#define HG_MIN_FLUSH_EVERY 20   /* 09: records (= 10 minutes x inputs + guardian) per flash write */')
rep('''  if (minN && (force || minN >= HG_MIN_FLUSH_EVERY || recsInFile >= 3600)) { if (!fileAppend("/log/min.bin", minBuf, (uint32_t)minN * HG_REC_SIZE)) ok = false; minN = 0; }''',
    '''  if (minN && (force || minN >= HG_MIN_FLUSH_EVERY)) { if (fileAppend(curPath, minBuf, (uint32_t)minN * HG_REC_SIZE)) recsInFile += minN; else { ok = false; recsLost += minN; } minN = 0; }''')
rep('  if (recsInFile >= 3600) newHourFile();', '  if (recsInFile >= HG_DAY_RECS) newHourFile();   /* 09: one file per day of minute records */')
rep('if (!hg_ring_boot_file(ringFiles, ringN, HG_HOUR_FILE_BYTES, &seq))', 'if (!hg_ring_boot_file(ringFiles, ringN, HG_DAY_FILE_BYTES, &seq))')
rep('#define HG_DCDC 1 ', '#define HG_DAY_RECS (2u * 1440u)\n#define HG_DAY_FILE_BYTES (24u + HG_DAY_RECS * 24u)\n#define HG_DCDC 1 ')
rep('    bool flushNow = (tick % 60000u == 0) || secN >= 60 || tick == 10000u || tick == 30000u;   // early flushes: short boots keep their seconds (T6a n2)',
    '    bool flushNow = (tick % 60000u == 0) || tick == 10000u || tick == 30000u;   // minute records are written every 10 min (HG_MIN_FLUSH_EVERY)')

# ---- haptics: the 08 button patterns stay; guardian patterns come from the layer
rep('static void vibrate(const uint8_t* pat) {\n  if (!hasDrv || lowBatMode) return;',
    'static void vibrate(const uint8_t* pat) {\n  if (!hasDrv) return;\n  if (lowBatMode || pofHold) pat = PAT_SOFT;   // R4 A8.2: low battery = soft tick only, never silent (T6b M1)')
rep('  if (!playing || millis() - motorStart > 5000) {', '  if (!playing || millis() - motorStart > 8000) {   // 09: HAP_CHECK runs 7 s (T6b m5)')
rep('static bool motorBusy = false;', 'static bool motorBusy = false;\nstatic bool pofHold = false;        // supply sagging (VBAT poll, see pofPoll): soft haptic tick only')

# ---- screen: the 08 status page becomes the diagnostic page; the product screens come from the layer
rep('static void drawStatus() {\n  if (!screenOn) return;', 'static void drawDiag() {\n  if (!screenOn) return;')
rep('  blTarget = lowBatMode ? BL_LOWBAT_PCT : BL_NORMAL_PCT;', '  blTarget = lowBatMode ? BL_LOWBAT_PCT : (uiAlert() ? BL_WARNING_PCT : BL_NORMAL_PCT);')
rep('const uint8_t  BL_NORMAL_PCT = 60, BL_MOTOR_MAX = 50, BL_LOWBAT_PCT = 20;', 'const uint8_t  BL_NORMAL_PCT = 60, BL_MOTOR_MAX = 50, BL_LOWBAT_PCT = 20, BL_WARNING_PCT = 100;\n'
    'static bool uiAlert(); static void fwSecond(const hg_rec_t*); static void uiButton(uint8_t); static bool eqi(const char*, const char*);\n'
    'static float accPeak = 0;   // max |a| this second for hg_fw (secAMean/secAM2/secAN are 08\'s own since 1.1.2)')
rep('#define C_GREY   RGB565(150, 150, 150)', '#define C_GREY   RGB565(150, 150, 150)\n#define C_BLUE   RGB565(40, 140, 255)\n#define C_YELLOW RGB565(255, 230, 0)')
rep('      if (m >= IMPACT_G) accImpact = true;', '      if (m >= IMPACT_G) accImpact = true;\n      if (m > accPeak) accPeak = m;')
rep('''    else if ((int32_t)(now - nextDraw) >= 0) { nextDraw = now + 1000; drawStatus(); }''',
    '''    else if ((int32_t)(now - nextDraw) >= 0) { nextDraw = now + 1000; uiDraw(false); }''')
rep('''    if ((int32_t)(now - screenOffAt) >= 0 && !motorBusy) screenSleep();''', '''    if ((int32_t)(now - screenOffAt) >= 0 && !motorBusy && !uiAlert()) screenSleep();''')
rep('''  screenWake(SCREEN_ON_MS);
  drawStatus();
  setupMs = millis();''', '''  guardianBoot();                                   // CRC check, profile, Body Twin file, guardian init
  screenWake(SCREEN_ON_MS);
  uiDraw(true);
  setupMs = millis();''')

# ---- button -> guardian (short = I'm OK / next page, long = HELP)
rep('''    else if (!longSent) { pendButton = true; queueMarker(HG_M_BUTTON, 0, "button"); vibrate(PAT_SHORT); }''',
    '''    else if (!longSent) { pendButton = true; queueMarker(HG_M_BUTTON, 0, "button"); uiButton(1); }''')
rep('''    queueMarker(HG_M_HELP, 0, "button-long");
    vibrate(PAT_LONG);''', '''    queueMarker(HG_M_HELP, 0, "button-long");
    uiButton(2);''')

# ---- BLE: custom service next to the console
rep('''  bleuart.begin();
  blebas.begin(); blebas.write(batteryPct(vbat));''', '''  bleuart.begin();
  hgBleBegin();                                    // HG service: STATUS / CMD / INFO
  blebas.begin(); blebas.write(batteryPct(vbat));''')
rep('  bledis.setModel("Band A 08_logger");\n  bledis.setFirmwareRev(HG_FW_VERSION);', '  bledis.setModel("Band A 09_guardian");\n  bledis.setFirmwareRev(HG_FW_VERSION " " HG2_NN_VERSION);')
rep('  Bluefruit.Advertising.addService(bleuart);', '  Bluefruit.Advertising.addService(hgSvc);')
rep('  Bluefruit.Advertising.start(0);\n}', '''  Bluefruit.Periph.setConnectCallback(hgOnConnect);
  Bluefruit.Periph.setDisconnectCallback(hgOnDisconnect);
  Bluefruit.Advertising.start(0);
}''')

# ---- commands
rep('''  else replyf(ch, "# unknown command: %s  (type help)\\n", argv[0]);''', '''  else if (guardianCommand(argc, argv, ch)) {}
  else replyf(ch, "# unknown command: %s  (type help)\\n", argv[0]);''')
rep('''    "#   erase YES            delete every log file (USB only)\\n",''', '''    "#   state | ring <n>     guardian state now | last n minutes of STATUS frames (hex)\\n",
    "#   profile <age> <sex 0/1> <bmi> <med bits>   the wearer (saved; e.g. profile 78 0 26 0)\\n",
    "#   log on|off           1 Hz debug records on USB + BLE UART\\n",
    "#   screen diag          the sensor page for 15 s\\n",
    "#   erase YES            delete every log file (USB only)\\n",''')
rep('  else if (eqi(argv[0], "screen")) screenWake(SCREEN_ON_MS);', '  else if (eqi(argv[0], "screen")) { uiPage = (argc >= 2 && eqi(argv[1], "diag")) ? UI_DIAG : UI_MAIN; screenWake(SCREEN_ON_MS); uiDraw(true); }')

# ---- loop: per-second guardian housekeeping, minute boundary, PPG duty, POF poll
rep('''    emitSecond(tick);
    accImpact = false;''', '''    guardianSecond(tick);                          // minute boundary FIRST (this second opens the new minute), PPG duty, haptics
    emitSecond(tick);
    accImpact = false; accPeak = 0;''')
rep('''  // battery every 10 s; low-battery mode with hysteresis''', '''  hgBleService();                                   // CMD queue, STATUS notify, DEBUG stream
  // battery every 10 s; low-battery mode with hysteresis''')
rep('''    blebas.write(batteryPct(vbat));''', '''    blebas.write(batteryPct(vbat));
    pofPoll();''')

# ---- stat: guardian lines
rep('''  if (rawActive) replyf(ch, "# STAT raw active''', '''  guardianStat(ch);
  if (rawActive) replyf(ch, "# STAT raw active''')

# ---- 07's icon helpers, copied unchanged into the layer
s07 = open("/home/claude/hg_fw/07_all_parts/07_all_parts.ino").read()
a07 = s07.index("static void thickLine(")
b07 = s07.index("static void drawLabel(")
layer = layer.replace("@@07_ICONS@@", "// --- from /home/claude/hg_fw/07_all_parts/07_all_parts.ino (read-only), verbatim ---\n" + s07[a07:b07])

# ---- insert the guardian layer before the command section
anchor = "// =====================================================================\n// commands (USB serial and BLE UART, one per line)"
rep(anchor, layer + "\n" + anchor)

# ---- shared driver files: byte copies of 08's (one source of truth)
import shutil
for fn in ["hg_i2c.c", "hg_i2c.h", "hg_ppg.c", "hg_ppg.h", "hg_ppg_coeffs.h", "log_ring.c", "log_ring.h", "log_format.h", "hg_nofastmath.h", "hg_astd.h"]:
    shutil.copyfile(os.path.join(R, "fw/08_logger", fn), os.path.join(R, "fw/09_guardian", fn))

out = os.path.join(R, "fw/09_guardian/09_guardian.ino")
open(out, "w").write(s)
print(f"wrote {out}: {s.count(chr(10))} lines")
